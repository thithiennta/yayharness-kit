# _yay_roadmap_build <combined doc> <out dir>: write what docs/roadmap/ should hold:
# README.md (front-matter, title, prose, then a generated index), one file per
# section, and a generated v<x.y.z>.md per target version. Generated files never
# start a line with `### R-` or `id: `, so they never count as IDs.
_yay_roadmap_build() {
  local c="$1" out="$2"
  awk -v out="$out" -v mark="<!-- $YAY_ROADMAP_MARK from the sprint files. Don't edit: change the sprint files (yayh roadmap add|set|move) and this follows. -->" \
      -v is="$YAY_ROADMAP_IDX_START" -v ie="$YAY_ROADMAP_IDX_END" '
    function cell(v) { if (v == "") return "-"; gsub(/\|/, "\\|", v); return v }
    function days(sz) { return sz == "S" ? 1.5 : sz == "M" ? 4 : sz == "L" ? 8 : 0 }
    function base(st) { sub(/:.*/, "", st); return st }
    function items(k) { return k (k == 1 ? " item" : " items") }
    function flush() {
      if (id == "") return
      n++; I_id[n] = id; I_ti[n] = title; I_st[n] = st; I_sz[n] = sz; I_tg[n] = tg; I_sec[n] = sec
      id = ""
    }
    BEGIN { pre = 1 }
    /^```/ { fence = !fence }
    !fence && /^## / {
      flush(); pre = 0; h = substr($0, 4)
      if (h ~ /^Sprint [0-9]+/) {
        k = h; sub(/^Sprint /, "", k); sub(/[^0-9].*/, "", k); sec = k; file = "sprint-" k ".md"
        s = ""; e = ""; rest = h
        if (match(rest, /[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]/)) { s = substr(rest, RSTART, 10); rest = substr(rest, RSTART + 10) }
        if (match(rest, /[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]/)) { e = substr(rest, RSTART, 10) }
        S_start[sec] = s; S_end[sec] = e; S_label[sec] = "Sprint " k
      } else {
        sec = tolower(h); sub(/[^a-z0-9-].*/, "", sec); if (sec == "") sec = "section"; file = sec ".md"; S_label[sec] = h
      }
      if (!(sec in seen)) { seen[sec] = 1; S[++ns] = sec; S_file[sec] = file; S_n[sec] = 0 }
      cur = out "/" file; S_body[sec] = S_body[sec] $0 "\n"; next
    }
    pre { P[++np] = $0; if ($0 ~ /^# / && name == "") { name = substr($0, 3); sub(/^Roadmap:[[:space:]]*/, "", name) } next }
    { S_body[sec] = S_body[sec] $0 "\n" }
    fence { next }
    /^### R-[0-9]+([[:space:]]|$)/ { flush(); id = $2; title = $0; sub(/^### R-[0-9]+[[:space:]]*/, "", title); st = ""; sz = ""; tg = ""; next }
    /^#/ { flush(); next }
    id == "" && /^Goal:/ && !(sec in S_goal) { g = $0; sub(/^Goal:[[:space:]]*/, "", g); S_goal[sec] = g; next }
    id != "" && /^- [a-z_]+:/ {
      k = $2; sub(/:$/, "", k); v = $0; sub(/^- [a-z_]+:[[:space:]]*/, "", v); sub(/[[:space:]]+$/, "", v)
      if (k == "status") st = v; else if (k == "size") sz = v; else if (k == "target") tg = v
    }
    END {
      flush()
      # section files, trailing blank lines trimmed
      for (j = 1; j <= ns; j++) {
        k = S[j]; b = S_body[k]; sub(/\n+$/, "\n", b); printf "%s", b > (out "/" S_file[k]); close(out "/" S_file[k])
      }
      for (i = 1; i <= n; i++) {
        k = I_sec[i]; S_n[k]++; b = base(I_st[i]); if (b != "dropped") S_dd[k] += days(I_sz[i]); if (b == "shipped") S_sh[k]++
        if (I_tg[i] != "" && !(I_tg[i] in vseen)) { vseen[I_tg[i]] = 1; V[++nv] = I_tg[i] }
      }
      # one generated file per target version
      for (j = 1; j <= nv; j++) {
        v = V[j]; p = out "/v" v ".md"
        cnt = 0; op = 0; ip = 0; sh = 0; dr = 0; last = ""; later = 0
        for (i = 1; i <= n; i++) if (I_tg[i] == v) {
          cnt++; b = base(I_st[i])
          if (b == "shipped") sh++; else if (b == "dropped") dr++; else if (b == "in-progress") ip++; else op++
          if (b != "shipped" && b != "dropped") { if (I_sec[i] ~ /^[0-9]+$/) { if (last == "" || I_sec[i] + 0 > last + 0) last = I_sec[i] } else later++ }
        }
        V_line[v] = sprintf("%s: %d open, %d in progress, %d shipped, %d dropped", items(cnt), op, ip, sh, dr)
        V_last[v] = last == "" ? "-" : "[Sprint " last "](sprint-" last ".md)" (S_end[last] != "" ? ", ends " S_end[last] : "")
        printf "%s\n# Version %s\n\n[Roadmap](README.md)\n\n%s.\n", mark, v, V_line[v] > p
        if (last != "") printf "The last open item is in %s: the earliest this version can ship.\n", V_last[v] > p
        if (later) printf "**%s not in a sprint yet**, so there is no ship date.\n", items(later) > p
        printf "\n| ID | Title | Status | Size | Sprint |\n|---|---|---|---|---|\n" > p
        for (i = 1; i <= n; i++) if (I_tg[i] == v) {
          k = I_sec[i]; sl = (k in S_file) ? "[" S_label[k] "](" S_file[k] ")" : "-"
          printf "| %s | %s | %s | %s | %s |\n", I_id[i], cell(I_ti[i]), cell(I_st[i]), cell(I_sz[i]), sl > p
        }
        close(p)
        printf "%s\t| [%s](v%s.md) | %s | %s |\n", v, v, v, V_line[v], V_last[v] > (out "/.versions")
      }
      close(out "/.versions")
      # README: what came before the first section, then the index
      while (np && P[np] ~ /^[[:space:]]*$/) np--
      p = out "/README.md"
      for (i = 1; i <= np; i++) print P[i] > p
      printf "\n%s\n**Sprints and sections**\n\n", is > p
      if (!ns) printf "_No sprints yet._\n" > p
      else printf "| Section | Dates | Goal | Items | Dev-days |\n|---|---|---|---|---|\n" > p
      for (j = 1; j <= ns; j++) {
        k = S[j]
        printf "| [%s](%s) | %s | %s | %d (%d shipped) | %g |\n", S_label[k], S_file[k], (S_start[k] != "" ? S_start[k] " → " S_end[k] : "-"), cell(S_goal[k]), S_n[k], S_sh[k], S_dd[k] > p
      }
      close(p)
    }' "$c"
  # versions sorted numerically, then the index end marker
  {
    if [ -s "$out/.versions" ]; then
      printf '\n**Versions**\n\n| Version | Items | Last open item |\n|---|---|---|\n'
      sort -t . -k1,1n -k2,2n -k3,3n "$out/.versions" | cut -f2-
    fi
    printf '%s\n' "$YAY_ROADMAP_IDX_END"
  } >> "$out/README.md"
  rm -f "$out/.versions"
}

# _yay_roadmap_owned <file>: a file in docs/roadmap/ that saving may replace or remove
# (README, a section file, a generated version list). Anything else is left alone.
_yay_roadmap_owned() {
  case "${1##*/}" in README.md) return 0 ;; esac
  awk 'NF { exit !(/^## / || index($0, "Generated by `yayh roadmap`")) } END { if (!NR) exit 1 }' "$1"
}

# _yay_roadmap_save <combined doc> [--check]: write the combined document back into
# docs/roadmap/. --check writes nothing and exits 1, listing the files that differ.
_yay_roadmap_save() {
  local c="$1" check="${2:-}" dir tmp f name diff=""
  dir="$(_yay_roadmap_dir)"; tmp="$(mktemp -d)"
  _yay_roadmap_build "$c" "$tmp"
  for f in "$tmp"/*.md; do
    name="${f##*/}"; cmp -s "$f" "$dir/$name" || diff="${diff}write	$name
"
  done
  for f in "$dir"/*.md; do
    [ -f "$f" ] || continue; name="${f##*/}"
    [ -f "$tmp/$name" ] && continue
    _yay_roadmap_owned "$f" && diff="${diff}remove	$name
"
  done
  if [ "$check" = --check ]; then
    rm -rf "$tmp"; [ -n "$diff" ] || return 0
    printf '%s' "$diff" | sed 's|	|	docs/roadmap/|'; return 1
  fi
  mkdir -p "$dir"
  printf '%s' "$diff" | while IFS="$YAY_TAB" read -r op name; do
    [ -n "$name" ] || continue
    case "$op" in write) cp "$tmp/$name" "$dir/$name" ;; remove) rm -f "$dir/$name" ;; esac
  done
  rm -rf "$tmp"
  # the cache now matches the files
  [ "$c" = "$(_yay_roadmap_cache)" ] && _yay_roadmap_stamp "$c" > "$c.stamp"
  printf '%s' "$diff" | sed 's|	|	docs/roadmap/|'
}

# yay_roadmap_split: convert docs/roadmap.md into docs/roadmap/ (one file per sprint),
# then remove docs/roadmap.md. Prints the files written.
yay_roadmap_split() {
  local root c; root="$(yay_repo_root)"
  case "$(yay_roadmap_layout)" in
    split) yay_die "docs/roadmap/ already exists" ;;
    none) yay_die "no docs/roadmap.md to split" ;;
  esac
  c="$(_yay_roadmap_cache)"; mkdir -p "$(dirname "$c")"
  cp "$root/docs/roadmap.md" "$c"
  mkdir -p "$root/docs/roadmap"
  _yay_roadmap_save "$c" >/dev/null
  rm -f "$root/docs/roadmap.md"
  _yay_roadmap_stamp "$c" > "$c.stamp"
  ( cd "$root" && ls docs/roadmap/*.md ) | sed 's/^/wrote	/'
  printf 'removed\tdocs/roadmap.md\n'
}

# yay_roadmap_render [--check]: rewrite the generated parts (README index, v<x.y.z>.md)
# after hand edits to the sprint files. --check exits 1 when they're out of date.
yay_roadmap_render() {
  local a check=""
  for a in "$@"; do case "$a" in --check) check=--check ;; *) yay_die "usage: yayh roadmap render [--check]" ;; esac; done
  [ "$(yay_roadmap_layout)" = split ] || yay_die "render needs the split layout (docs/roadmap/); run yayh roadmap split"
  local c out; c="$(_yay_roadmap_need)"
  out="$(_yay_roadmap_save "$c" $check)" || { printf '%s\n' "$out"; return 1; }
  if [ -n "$out" ]; then printf '%s\n' "$out"; else printf 'unchanged\tdocs/roadmap/\n'; fi
}
